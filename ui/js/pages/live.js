export function liveText(value) {
  if (Object.hasOwn(LIVE_TEXT_KEYS, value)) return translateUI(LIVE_TEXT_KEYS[value]);
  if (typeof value !== 'string') return value;
  const retry = /^(.*) — retrying in (\d+)s$/.exec(value);
  return retry ? translateUI('liveui.retry', { error: retry[1], seconds: retry[2] }) : uiLabel(value);
}
