"""Original Companion region maps — layout source (DEVELOPER DATA, drawn for this project).

Every coordinate here was laid out by hand for the Companion on a simple grid (1 unit = 10 px). Nothing is traced
or copied from game graphics, ROM extracts, Synergy, Serebii or any other map: the layouts only follow the publicly
known *topology* of each region (which town connects to which route, roughly in which direction).

Feature fields
  id      stable feature id (used for click targets; never reuse for another place)
  name    label shown on the map
  kind    town | route | sea | cave | landmark | area
  at      (x, y) for towns / caves / landmarks / areas
  path    list of polylines (each a list of points or town ids) for routes and sea routes
  locs    location names in the PokeMMO data this place opens; "Name*" also matches "Name (…)" sub-areas/floors
  land    False for features that must not add land (sea routes)
Region fields: size (grid w, h), extra land blobs, mountains, forests, lakes, submaps.
"""

T = "town"; R = "route"; S = "sea"; C = "cave"; L = "landmark"; A = "area"


def town(i, name, x, y, locs=None, big=False):
    # towns are linked to their own encounter table when the data has one ("?" = optional: many towns have no wild Pokémon)
    return {"id": i, "name": name, "kind": T, "at": (x, y), "locs": locs if locs is not None else ["?" + name], "big": big}


def route(i, name, *path, locs=None, sea=False):
    lines = [list(p) for p in path] if all(isinstance(p, list) for p in path) else [list(path)]
    return {"id": i, "name": name, "kind": S if sea else R, "path": lines, "locs": locs if locs is not None else [name]}


def place(i, name, x, y, kind=C, locs=None):
    return {"id": i, "name": name, "kind": kind, "at": (x, y), "locs": locs if locs is not None else [name + "*"]}


